FIXTURE_SHA = "148974fecd2dca20e4e8050e4ee98d59ad0e2afbad7fa672dc9d9f5acffe284e"


def _pdf():
    document = pymupdf.open()
    page = document.new_page()
    page.insert_text((50, 50), "This authored PDF contains ordinary selectable text and no generation claim.")
    return document


def _entry(data):
    adapter = PdfCredentialsDetector()
    ctx = SimpleNamespace(media=SimpleNamespace(original_bytes=lambda: data),
                          exhibits=SimpleNamespace(table=Mock(return_value="table")))
    return detector_entry(adapter.spec, adapter.run(ctx), "pdf-credentials-test")


def test_unsigned_pdf_and_non_pdf_prose_continue():
    with _pdf() as document:
        entry = _entry(document.tobytes())
    assert entry["status"] == "not_applicable"
    assert provenance_gate.decide({"detectors": [entry]}, "document")["action"] == "continue_detection"
    entry = _entry(b"Generated by OpenAI.  \xe2\x80\x8b  Content Credentials.")
    assert entry["status"] == "not_applicable"
    assert provenance_gate.decide({"detectors": [entry]}, "document")["action"] == "continue_detection"


def test_catalog_association_requires_the_same_file_specification():
    marker = b"\x00\x00\x00\x0cjumbtest"
    with _pdf() as document:
        assert pdf_credentials.catalog_store(document.tobytes()) is None
        document.embfile_add("Claim", marker)
        catalog = document.pdf_catalog()
        assert pdf_credentials.catalog_store(document.tobytes()) is None
        stream_number = document.xref_length() - 1
        filespec = document.get_new_xref()
        document.update_object(filespec, f"<< /Type /Filespec /AFRelationship /C2PA_Manifest /EF << /F {stream_number} 0 R >> >>")
        document.xref_set_key(catalog, "Names/EmbeddedFiles/Names", f"[(Claim) {filespec} 0 R]")
        document.xref_set_key(catalog, "AF", f"[{filespec} 0 R]")
        assert pdf_credentials.catalog_store(document.tobytes()) == marker
        document.xref_set_key(catalog, "AF", f"[{filespec} 0 R {filespec} 0 R]")
        assert pdf_credentials.catalog_store(document.tobytes()) is None


def test_pdf_parse_timeout_is_inconclusive(monkeypatch):
    from subprocess import TimeoutExpired

    run = Mock(side_effect=TimeoutExpired("offline PDF check", pdf_credentials.TIMEOUT))
    monkeypatch.setattr(pdf_credentials.subprocess, "run", run)
    report, binding = pdf_credentials.read(b"%PDF-")
    assert report.state == "unreadable" and not binding


@pytest.fixture(scope="module")
def provider_pdf():
    if not (path := os.environ.get("CHIPMUNK_SIGNED_PDF_FIXTURE")):
        pytest.skip("Set CHIPMUNK_SIGNED_PDF_FIXTURE to the pinned public fixture described in docs")
    data = Path(path).read_bytes()
    assert hashlib.sha256(data).hexdigest() == FIXTURE_SHA
    return data


def test_actual_provider_signature_and_bound_controls(provider_pdf, tmp_path):
    original = _entry(provider_pdf)
    assert original["metrics"]["pdf_document_binding"] == 1
    assert provenance_gate.decide({"detectors": [original]}, "document")["action"] == "stop_statistical_detection"
    original["metrics"].pop("pdf_document_binding")
    assert provenance_gate.decide({"detectors": [original]}, "document")["action"] == "continue_detection"

    edited = tmp_path / "incremental.pdf"
    edited.write_bytes(provider_pdf)
    with pymupdf.open(edited) as pdf:
        pdf[0].insert_text((30, 35), "A later visible note.")
        pdf.saveIncr()
    with _pdf() as pdf:
        manifest = pdf_credentials.catalog_store(provider_pdf)
        assert manifest is not None
        pdf.embfile_add("Content Credentials", manifest)
        attached = pdf.tobytes()
    with pymupdf.open(stream=provider_pdf) as pdf:
        pdf.xref_set_key(pdf.pdf_catalog(), "AF", "null")
        no_catalog = pdf.tobytes()
    for data in (edited.read_bytes(), attached, no_catalog):
        assert provenance_gate.decide({"detectors": [_entry(data)]}, "document")["action"] == "continue_detection"


def _verify_public_package(billing, analysis, db, frozen, pdf, tmp_path):
    from zipfile import ZipFile

    from app.reports import package, signing, verify, verify_document_source
    from app.storage.db import ReportRow

    key = signing.instance_key(tmp_path / "signing-key.pem")
    report_pdf = register_artefact(db, billing.store, pdf, media_type="application/pdf", role="report",
                                   created_by="fixture", analysis_id=analysis.id)
    report_snapshot = register_artefact(db, billing.store, snapshot.dump(frozen), media_type="application/json",
        role="stage_output", created_by="fixture", analysis_id=analysis.id)
    report = ReportRow(id=frozen.report.id, display_id=frozen.report.display_id, revision=1, analysis_id=analysis.id,
        analysis_revision=analysis.revision, profile="standard", redacted=False, review_state="machine", issuable=False,
        template_set=engine.TEMPLATE_SET, engine="fixture", status="done", snapshot_hash=snapshot.snapshot_hash(frozen),
        snapshot_artefact_id=report_snapshot.id, artefact_id=report_pdf.id, sha256=report_pdf.sha256, signature=key.sign(pdf),
        signing_key_id=key.key_id, requested_by="fixture", requested_at=datetime.now(UTC), page_count=1)
    db.add(report)
    db.flush()
    request = package.prepare(db, analysis, report, kind="draft", include_original=False, created_by="fixture",
                              schema_id=package.PUBLIC_SCHEMA)
    built = package.build(db, request, store=billing.store, key=key, exported_at=datetime.now(UTC))
    checked = verify.verify_package(built.path, public_key_pem=key.public_pem())
    assert checked.ok, checked.as_dict()
    with ZipFile(built.path) as archive:
        assert archive.read("report.pdf") == pdf
        result = json.loads(archive.read("result.json"))
        assert result["decision"]["code"] == "ai_supported"
        original = tmp_path / "verified-source.pdf"
        original.write_bytes(billing.store.read_bytes(analysis.sha256))
        verified = verify_document_source.check(archive, json.loads(archive.read("bundle.json")), original)
        assert "matched" in verified or "verified" in verified.lower()


@pytest.mark.parametrize("profile", ["quick", "full", "deep"])
def test_signed_provider_pdf_waits_for_payment_and_skips_writing_models(billing, provider_pdf, profile, monkeypatch, tmp_path):
    monkeypatch.setattr(settings, "document_pdf_credentials", True)
    purchase = billing.client.post("/api/v2/billing/checkout", headers={**billing.headers, "Idempotency-Key": str(uuid.uuid4())},
        data={"kind": "document", "profile": profile, "risk_accepted": "true", "risk_notice_version": purchase_notice.VERSION,
              "risk_notice_sha256": purchase_notice.SHA256}, files={"file": ("provider.pdf", provider_pdf, "application/pdf")})
    assert purchase.status_code == 201, purchase.text
    order = purchase.json()["order_id"]
    assert counts(billing) == (0, 0, 0)
    assert billing.created[0][0]["line_items[0][price_data][unit_amount]"] == 999
    assert signed(billing, event_for(billing, order, paid=False)).status_code == 200
    assert counts(billing) == (0, 0, 0)
    assert signed(billing, event_for(billing, order)).status_code == 200
    assert counts(billing) == (1, 1, 1)
    ident = billing.client.get(f"/api/v2/billing/orders/{order}", headers=billing.headers).json()["analysis_id"]
    from app.billing.entitlements import require_analysis_payment

    with billing.sessions() as db:
        require_analysis_payment(db, db.get(Analysis, ident))
    models = SimpleNamespace(lease=Mock(side_effect=AssertionError("Unexpected model lease")))
    outcome = pipelines.run_analysis(ident, profile=profile, sessions=billing.sessions, store=billing.store, models=models)
    assert outcome.status == "done", (outcome.status, outcome.error, outcome.stages)
    models.lease.assert_not_called()
    assert outcome.outputs["provenance_gate"]["action"] == "stop_statistical_detection"
    assert outcome.outputs["detect"]["detectors"] and all(row["status"] == "skipped" for row in outcome.outputs["detect"]["detectors"])
    decision = outcome.outputs["fuse"]["decision"]
    assert decision["provenance_record"]["kind"] == "decisive_ai" and decision["probability_ai_uncalibrated"] is None
    with billing.sessions() as db:
        analysis = db.get(Analysis, ident)
        raw = json.loads(billing.store.read_bytes(analysis.result_hash))
        public = public_package.public_result(raw)
        assert public["decision"]["code"] == "ai_supported"
        assert "Statistical writing checks were skipped" in json.dumps(public)
        assert not any(name in json.dumps(public).lower() for name in ("deberta", "binoculars", "tropa", "desklib"))
        if profile == "quick":
            frozen = snapshot.build(db, analysis, raw, report_id=str(uuid.uuid4()), revision=1, profile="standard",
                redacted=False, supersedes_report_id=None, revision_reason=None, requested_at=datetime.now(UTC),
                requested_by="authored-payment-check", template_set=engine.TEMPLATE_SET,
                veritas_version=settings.version, store=billing.store)
            pdf = engine.render_pdf(frozen).pdf
            text = " ".join(engine.pdf_text(pdf).split())
            assert "Statistical writing checks were skipped" in text
            assert not any(name in text.lower() for name in ("deberta", "binoculars", "tropa", "desklib"))
            _verify_public_package(billing, analysis, db, frozen, pdf, tmp_path)
            if path := os.environ.get("CHIPMUNK_PDF_CREDENTIALS_SMOKE_DIR"):
                target = Path(path)
                (target / "report.pdf").write_bytes(pdf)
                (target / "public.json").write_text(json.dumps(public, indent=2))
