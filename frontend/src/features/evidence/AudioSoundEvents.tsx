import { useEffect, useState } from 'react'
import { useLocation } from 'react-router-dom'
import { EvidenceAudio, EvidenceLimits, EvidencePicture, evidenceGrid } from './EvidenceMedia'
import { rationalSeconds, seconds, type AudioEvidenceSet } from './multimediaPackets'

/** Recorded category responses are listening context, not authenticity evidence. */
export default function AudioSoundEvents({ set, token, mediaReady, pauseAudio }: {
  set: AudioEvidenceSet; token: string; mediaReady: boolean; pauseAudio: () => void
}) {
  const context = set.sound_events, { hash } = useLocation()
  const [selectedId, setSelectedId] = useState(context?.windows[0]?.id)
  useEffect(() => {
    const window = context?.windows.find((item) => hash === `#media-evidence-${item.id}`)
    if (window) { pauseAudio(); setSelectedId(window.id) }
  }, [hash, context])
  if (!context) return null
  const bound = context.schema === 'chipmunk.sound-events/1' && context.status === 'ready'
    && context.source.sha256 === set.source.sha256 && context.source.pcm_sha256 === set.source.pcm_sha256
    && context.source.sample_rate === set.source.sample_rate && context.source.sample_rate === 16000
    && context.source.samples === (set.coverage?.decoded_samples ?? set.source.samples)
  const selected = context.windows.find((item) => item.id === selectedId) ?? context.windows[0]
  return <section id="media-evidence-sounds" aria-label="Possible background sounds" className="mt-5 rounded-md border border-border p-4 scroll-mt-20">
    <h3 className="m-0 text-body font-medium">Possible sounds in this recording</h3>
    {!bound ? <p role="alert">Sound categories do not match this analyzed source; clips and charts cannot be shown.</p> : <>
      <p className="mt-2 text-small text-text-muted">Listen for possible speech, music and environmental sounds in each interval. These categories describe the mixed track; they do not establish whether a voice or recording was generated by AI.</p>
      <div role="group" aria-label="Choose a sound-category interval" className="flex flex-wrap gap-2">
        {context.windows.map((item) => <button type="button" key={item.id} aria-pressed={selected?.id === item.id}
          aria-controls={`media-evidence-${item.id}`} onClick={() => { pauseAudio(); setSelectedId(item.id) }}
          className={`rounded-sm border px-3 py-2 text-left ${selected?.id === item.id ? 'border-accent bg-surface-2 ring-1 ring-accent' : 'border-border'}`}>
          <span className="font-mono">{item.id} · {seconds(item.start_s)}–{seconds(item.end_s)}</span>
          <span className="block text-small">{item.labels[0]?.label}</span>
        </button>)}
      </div>
      {context.windows.map((item) => <article key={item.id} id={`media-evidence-${item.id}`} hidden={item.id !== selected?.id}
        aria-label={`Sound categories ${item.id}`} className="mt-4 border-t border-border pt-4 scroll-mt-20">
        <h4 className="m-0 text-body font-medium">{item.id} · {seconds(item.start_s)}–{seconds(item.end_s)}</h4>
        <p className="text-small">Possible categories: {item.labels.map((v) => `${v.label} (score ${v.score.toFixed(3)})`).join('; ')}.</p>
        <p className="text-caption text-text-muted">Scores rank categories across the entire selected interval. They are not AI confidence percentages or exact event boundaries. Source samples [{item.start_sample}, {item.end_sample}).</p>
        <div className={evidenceGrid}>
          <EvidencePicture set={set} artifact={item.artifacts.waveform} token={token} ready={mediaReady} chart alt={`${item.id}: waveform of the sound-category interval`} />
          <EvidenceAudio set={set} artifact={item.artifacts.selected_clip} token={token} ready={mediaReady} alt={`${item.id}: exact sound-category interval`} />
        </div>
        <details className="mt-3 text-caption"><summary>Original recording timestamps</summary><ul>
          {item.source_timestamp_ranges.map((range, i) => {
            const a = rationalSeconds(range.source_start_pts, range.time_base), b = rationalSeconds(range.source_end_pts, range.time_base)
            return <li key={i}>Samples [{range.start_sample}, {range.end_sample}): {a !== null && b !== null ? `${seconds(a)}–${seconds(b)}` : 'Unavailable'}</li>
          })}
        </ul></details>
      </article>)}
      {!context.windows.length && <p>No complete sound-category window was recorded.</p>}
      <EvidenceLimits lines={context.limitations} />
    </>}
  </section>
}
